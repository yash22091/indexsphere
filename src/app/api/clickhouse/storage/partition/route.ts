/**
 * POST /api/clickhouse/storage/partition { database, table, partitionId, action }
 *   action: 'optimize' — OPTIMIZE TABLE … PARTITION ID … FINAL (operator/admin)
 *           'drop'     — ALTER TABLE … DROP PARTITION ID …      (admin; the UI asks to type the partition)
 * ClickHouse's own max_partition_size_to_drop guard still applies.
 */
import { NextRequest, NextResponse } from 'next/server';
import { requireClickHouseSession } from '@/lib/cluster-session';
import { chErrorResponse, chRoleDenied } from '@/lib/clickhouse-api';
import { quoteIdent } from '@/lib/clickhouse-sql';
import { writeAuditLog } from '@/lib/audit';

// Partition IDs are generated by ClickHouse: digits, hex hashes, "all", or values joined by "-"/"_"
const PARTITION_ID = /^[A-Za-z0-9_-]{1,256}$/;

export async function POST(request: NextRequest) {
  const ctx = requireClickHouseSession(request);
  if (ctx instanceof NextResponse) return ctx;
  const { user, session } = ctx;

  const { database, table, partitionId, action } = await request.json().catch(() => ({}));
  if (typeof database !== 'string' || typeof table !== 'string' || !database || !table) {
    return NextResponse.json({ error: 'database and table are required' }, { status: 400 });
  }
  if (typeof partitionId !== 'string' || !PARTITION_ID.test(partitionId)) {
    return NextResponse.json({ error: 'Invalid partition ID' }, { status: 400 });
  }
  if (action !== 'optimize' && action !== 'drop') return NextResponse.json({ error: 'action must be optimize or drop' }, { status: 400 });
  const denied = chRoleDenied(user.role, action === 'drop' ? 'admin' : 'write');
  if (denied) return denied;

  try {
    // Only MergeTree-family tables have partitions; also confirms the table exists
    const t = await session.client.query<{ engine: string }>(
      'SELECT engine FROM system.tables WHERE database = {db:String} AND name = {t:String}',
      { role: user.role, params: { db: database, t: table } },
    );
    if (!t.data[0]) return NextResponse.json({ error: 'Table not found' }, { status: 404 });
    if (!/MergeTree/.test(t.data[0].engine)) return NextResponse.json({ error: 'Not a MergeTree table' }, { status: 400 });

    const fq = `${quoteIdent(database)}.${quoteIdent(table)}`;
    const sql = action === 'optimize'
      ? `OPTIMIZE TABLE ${fq} PARTITION ID '${partitionId}' FINAL`
      : `ALTER TABLE ${fq} DROP PARTITION ID '${partitionId}'`;
    // A FINAL merge of a large partition can take minutes
    await session.client.query(sql, { role: user.role, settings: { max_execution_time: action === 'optimize' ? 600 : 120 } });
    writeAuditLog(request, `clickhouse:partition-${action}`, { target: `${database}.${table}:${partitionId}`, statusCode: 200 });
    return NextResponse.json({ ok: true });
  } catch (err) {
    return chErrorResponse(err);
  }
}
